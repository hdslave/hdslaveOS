"""The panel's type as a C header: Spleen (BSD 2-Clause, Frederic Cambus; `make fonts` fetches it), a bitmap face,
at its own sizes and drawn without smoothing so every pixel stays sharp:
  sp_label  6 x 12   knob labels, the preset's name, small text
  sp_value  8 x 16   values
  sp_big   12 x 24   page titles and the wheel's value

    python3 fonts.py FONTDIR fonts.h

Printable ASCII; each glyph an 8-bit coverage map of its ink (which may reach past its advance), one row per pixel
of the font's height. Needs Pillow."""
import sys
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

font_dir, output = map(Path, sys.argv[1:])


def face(name, file, size):
    font = ImageFont.truetype(str(font_dir / file), size)
    ascent, descent = font.getmetrics()
    height = ascent + descent
    glyphs, pixels = [], []
    for code in range(32, 127):
        ch = chr(code)
        advance = round(font.getlength(ch))
        left, _, right, _ = font.getbbox(ch) if ch != ' ' else (0, 0, advance, 0)
        x0, x1 = min(0, left), max(advance, right)
        width = max(1, x1 - x0)
        image = Image.new('L', (width, height))
        draw = ImageDraw.Draw(image)
        draw.fontmode = '1'  # a bitmap face at its own size: no smoothing
        draw.text((-x0, 0), ch, font=font, fill=255)
        glyphs.append((len(pixels), width, advance, x0))
        pixels.extend(image.getdata())
    return name, glyphs, pixels, height, ascent


FACES = [
    face('sp_label', 'spleen-6x12.otf', 12),
    face('sp_value', 'spleen-8x16.otf', 16),
    face('sp_big', 'spleen-12x24.otf', 24),
]

parts = ['// Generated by experiments/lo-fly/fonts.py from Spleen (BSD 2-Clause). Do not edit.']
for name, glyphs, pixels, height, ascent in FACES:
    parts.append(f'static constexpr Glyph {name}_glyphs[] = {{' + ','.join('{%d,%d,%d,%d}' % g for g in glyphs) + '};')
    parts.append(f'static constexpr unsigned char {name}_pixels[] = {{' + ','.join(map(str, pixels)) + '};')
    parts.append(f'static constexpr Font {name}_font {{{name}_glyphs, {name}_pixels, {height}, {ascent}}};')
output.parent.mkdir(parents=True, exist_ok=True)
output.write_text('\n'.join(parts) + '\n')
