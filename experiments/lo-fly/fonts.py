"""Rasterise the panel's faces into a C header.

    python3 fonts.py FONTDIR fonts.h

FONTDIR holds PatrickHand-Regular.ttf and Caveat-VF.ttf, from Google Fonts (SIL OFL 1.1; `make fonts` fetches them).
Printable ASCII; each glyph an 8-bit coverage map of its ink (which may reach past its advance), one row per pixel
of the font's height. Needs Pillow."""
import sys
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

font_dir, output = map(Path, sys.argv[1:])
# name, file, pixel size, variable axes by name
FACES = [
    ('ph_small', 'PatrickHand-Regular.ttf', 14, {}), ('ph_label', 'PatrickHand-Regular.ttf', 15, {}),
    ('ph_value', 'PatrickHand-Regular.ttf', 18, {}),
    ('cv_title', 'Caveat-VF.ttf', 22, {'Weight': 700}), ('cv_big', 'Caveat-VF.ttf', 27, {'Weight': 700}),
]

parts = ['// Generated by experiments/lo-fly/fonts.py from Patrick Hand and Caveat (SIL OFL 1.1). Do not edit.']
for name, file, size, axes in FACES:
    font = ImageFont.truetype(str(font_dir / file), size)
    if axes:
        values = []
        for axis in font.get_variation_axes():
            key = axis['name'].decode() if isinstance(axis['name'], bytes) else axis['name']
            values.append(axes.get(key, axis['default']))
        font.set_variation_by_axes(values)
    ascent, descent = font.getmetrics()
    height = ascent + descent
    glyphs, pixels = [], []
    for code in range(32, 127):
        ch = chr(code)
        advance = round(font.getlength(ch))
        left, _, right, _ = font.getbbox(ch) if ch != ' ' else (0, 0, advance, 0)
        x0, x1 = min(0, left), max(advance, right)  # script faces reach past their advance
        width = max(1, x1 - x0)
        image = Image.new('L', (width, height))
        ImageDraw.Draw(image).text((-x0, 0), ch, font=font, fill=255)
        glyphs.append((len(pixels), width, advance, x0))
        pixels.extend(image.getdata())
    parts.append(f'static constexpr Glyph {name}_glyphs[] = {{' + ','.join('{%d,%d,%d,%d}' % g for g in glyphs) + '};')
    parts.append(f'static constexpr unsigned char {name}_pixels[] = {{' + ','.join(map(str, pixels)) + '};')
    parts.append(f'static constexpr Font {name}_font {{{name}_glyphs, {name}_pixels, {height}, {ascent}}};')
output.parent.mkdir(parents=True, exist_ok=True)
output.write_text('\n'.join(parts) + '\n')
